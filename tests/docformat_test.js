function open(file) {
  return new DocxPackage(fs.readFileSync(file));
}

function bodyParas(pkg) {
  const scan = xml.scanParagraphs(pkg.getText(pkg.mainDocumentName));
  return scan.paragraphs.filter((x) => !x.inTable);
}

function margins(pkg) {
  const doc = pkg.getText(pkg.mainDocumentName);
  const mar = /<w:pgMar\b[^>]*\/>/.exec(doc)[0];
  const get = (n) => +(Number(new RegExp('w:' + n + '="(-?\\d+)"').exec(mar)[1]) / 567).toFixed(2);
  return { top: get('top'), bottom: get('bottom'), left: get('left'), right: get('right') };
}

