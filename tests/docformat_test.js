function p(text, opts) {
  const o = opts || {};
  const rPr = o.font
    ? '<w:rPr><w:rFonts w:ascii="' + o.font + '" w:eastAsia="' + o.font + '" w:hAnsi="' + o.font +
      '"/><w:sz w:val="' + (o.size || 21) + '"/></w:rPr>'
    : '';
  const spacing = '<w:spacing w:line="' + (o.line || 240) + '" w:lineRule="auto"/>';
  const ind = o.indent === undefined ? '' : '<w:ind w:firstLine="' + o.indent + '"/>';
  const jc = o.align ? '<w:jc w:val="' + o.align + '"/>' : '';
  const pPr = '<w:pPr>' + spacing + ind + jc + '</w:pPr>';
  if (!text) return '<w:p>' + pPr + '</w:p>';
  return '<w:p>' + pPr + '<w:r>' + rPr + '<w:t xml:space="preserve">' +
    xml.escapeText(text) + '</w:t></w:r></w:p>';
}

